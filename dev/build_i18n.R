#!/usr/bin/env Rscript
# Generate www/js/i18n.js from i18n/translations.csv.
# Run after every change to the translation table.

args <- commandArgs(trailingOnly = FALSE)
file_arg <- sub("^--file=", "", args[grepl("^--file=", args)])
root <- if (length(file_arg)) dirname(dirname(normalizePath(file_arg))) else normalizePath(".")
csv <- file.path(root, "i18n", "translations.csv")
out <- file.path(root, "www", "js", "i18n.js")
dir.create(dirname(out), recursive = TRUE, showWarnings = FALSE)

tab <- utils::read.csv(csv, stringsAsFactors = FALSE, check.names = FALSE,
                       encoding = "UTF-8", na.strings = character())
stopifnot(all(c("key", "en", "zh") %in% names(tab)))
stopifnot(!anyDuplicated(tab$key))
stopifnot(all(nzchar(tab$en)), all(nzchar(tab$zh)))

dict <- list(
  en = stats::setNames(as.list(tab$en), tab$key),
  zh = stats::setNames(as.list(tab$zh), tab$key)
)
json <- jsonlite::toJSON(dict, auto_unbox = TRUE, ensure_ascii = FALSE,
                         pretty = TRUE, null = "null")
meta <- jsonlite::toJSON(
  list(keys = nrow(tab), generated = format(Sys.time(), tz = "UTC"),
       source = "i18n/translations.csv"),
  auto_unbox = TRUE, ensure_ascii = FALSE
)

lines <- c(
  "/* Generated by dev/build_i18n.R. Do not edit by hand. */",
  paste0("window.MCMC3R_I18N = ", json, ";"),
  paste0("window.MCMC3R_I18N_META = ", meta, ";")
)
writeLines(lines, out, useBytes = TRUE)
cat("Wrote", out, "with", nrow(tab), "keys\n")
